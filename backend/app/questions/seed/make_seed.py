def main(out: str) -> None:
    rnd = random.Random(2026)
    rows = []
    seen = set()
    for category, parts in DATA.items():
        for text, correct, w1, w2, w3, diff in parts["mcq"]:
            assert text not in seen, text
            seen.add(text)
            opts = [correct, w1, w2, w3]
            assert len(set(opts)) == 4, text
            order = list(range(4))
            rnd.shuffle(order)
            rows.append(
                {
                    "type": "mcq",
                    "category": category,
                    "difficulty": diff,
                    "text_ar": text,
                    "options_ar": [opts[i] for i in order],
                    "correct_index": order.index(0),
                    "source": "harb-seed",
                }
            )
        for text, answer, unit, diff in parts["num"]:
            assert text not in seen, text
            seen.add(text)
            rows.append(
                {
                    "type": "numeric",
                    "category": category,
                    "difficulty": diff,
                    "text_ar": text,
                    "numeric_answer": answer,
                    "unit_ar": unit,
                    "source": "harb-seed",
                }
            )
    with open(out, "w", encoding="utf-8") as f:
        json.dump(rows, f, ensure_ascii=False, indent=1)
    by_cat = {}
    for r in rows:
        by_cat.setdefault(r["category"], [0, 0])[r["type"] == "numeric"] += 1
    print(len(rows), "questions", by_cat)


if __name__ == "__main__":
    main(sys.argv[1])
